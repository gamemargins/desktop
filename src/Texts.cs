        public static string Language = "en";

        /// <summary>The language the site named, else Windows' when it is one of ours, else English.</summary>
        public static string Pick(string locale)
        {
            var wanted = (locale ?? "").ToLowerInvariant();
            if (wanted.Length == 0)
            {
                var ui = CultureInfo.CurrentUICulture;
                wanted = ui.Name.Equals("pt-BR", System.StringComparison.OrdinalIgnoreCase) ? "pt-br" : ui.TwoLetterISOLanguageName.ToLowerInvariant();
                if (wanted == "pt") wanted = "pt-br";
            }
            foreach (var l in Languages) if (l == wanted) return l;
            return "en";
        }

        /// <summary>Numbers and times in the language's style: 151,749 in English, 151.749 in Dutch, 151 749 in French.</summary>
        public static CultureInfo Culture
        {
            get
            {
                switch (Language)
                {
                    case "nl": return CultureInfo.GetCultureInfo("nl-NL");
                    case "de": return CultureInfo.GetCultureInfo("de-DE");
                    case "fr": return CultureInfo.GetCultureInfo("fr-FR");
                    case "es": return CultureInfo.GetCultureInfo("es-ES");
                    case "pt-br": return CultureInfo.GetCultureInfo("pt-BR");
                    default: return CultureInfo.GetCultureInfo("en-GB");
                }
            }
        }

        public static string T(string en)
        {
            Dictionary<string, string> table;
            string text;
            if (Language != "en" && All.TryGetValue(Language, out table) && table.TryGetValue(en, out text)) return text;
            return en;
        }

        public static string T(string en, params object[] args)
        {
            return string.Format(Culture, T(en), args);
        }

